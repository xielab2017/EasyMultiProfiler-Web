root <- normalizePath('.')
target <- tempfile('emp-background-');dir.create(target)
Sys.setenv(EMP_DATA_DIR=target,EMP_BACKEND_DIR=file.path(root,'webapp/backend'),BACKEND_DIR=file.path(root,'webapp/backend'),EMP_ROOT=root)
suppressPackageStartupMessages({library(EasyMultiProfiler);library(SummarizedExperiment);library(MultiAssayExperiment);library(jsonlite)})
files <- list.files('webapp/backend/helpers',pattern='\\.R$',full.names=TRUE)
source('webapp/backend/helpers/storage.R')
for(f in files[basename(files)!='storage.R'])source(f)
sid <- emp_create_owned_session('local')
a <- matrix(as.numeric(1:24),4,dimnames=list(paste0('g',1:4),paste0('s',1:6)))
se <- SummarizedExperiment(assays=list(counts=a),colData=S4Vectors::DataFrame(group=rep(c('A','B'),each=3),row.names=colnames(a)))
rowData(se)$feature <- rownames(se)
rowData(se)$Name <- rownames(se)
mae <- MultiAssayExperiment(experiments=list(test=se))
save_mae(sid,mae)
handlers <- emp_background_handlers()
stopifnot('/prepare/filter'%in%names(handlers),!'/user_r/run'%in%names(handlers),!'/tasks/submit'%in%names(handlers),!'/workflows/rnaseq/run_all'%in%names(handlers))
id <- submit_job('analysis:/prepare/filter','emp_run_background_request',list(route='/prepare/filter',payload=list(session_id=sid,experiment='test',min_count=22),principal='local'),session_id=sid,owner_id='local')
cat('Synthetic background task:',id,'\n')
for(i in 1:90){Sys.sleep(1);st<-get_job_status(id);if(st$status%in%c('done','error'))break}
if(st$status!='done'){cat(readLines(.job_log_path(id)),sep='\n');stop(st$error%||%st$status)}
r <- get_job_result(id);stopifnot(r$success,r$kept==3,r$removed==1)
rows<-list_jobs(owner_id='local');stopifnot(length(rows)==1,!is.null(rows[[1]]$pid),!is.null(rows[[1]]$finished))
stopifnot(length(list_jobs(owner_id='other'))==0)
lock <- .job_session_lock(sid)
id2 <- submit_job('analysis:/prepare/filter','emp_run_background_request',list(route='/prepare/filter',payload=list(session_id=sid,experiment='test',min_count=100),principal='local'),session_id=sid,owner_id='local')
for(i in 1:45){Sys.sleep(1);queued<-get_job_status(id2);if(grepl('Waiting for another',queued$message))break}
stopifnot(queued$status=='queued',grepl('Waiting for another',queued$message))
stopifnot(cancel_job(id2)$status=='cancelled',get_job_status(id2)$status=='cancelled')
unlink(lock,recursive=TRUE)
stopifnot(nrow(assay(load_empt(sid,'test')))==3L)
cat('Background worker, queue, cancellation, result, ownership and process summary passed.\n')
unlink(target,recursive=TRUE)
