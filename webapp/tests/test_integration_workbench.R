source('webapp/backend/helpers/integration_workbench.R')
set.seed(20261107)
subjects <- paste0('simulated_subject_', 1:8)
blocks <- lapply(seq_along(.iw_omics), function(i) {
  mat <- matrix(rnorm(8 * 6), nrow = 6, dimnames = list(paste0('feature_',1:6), paste0('assay',i,'_',1:8)))
  csv <- paste(capture.output(write.csv(data.frame(feature_id=rownames(mat),mat,check.names=FALSE),row.names=FALSE)),collapse='\n')
  list(id=paste0('block_',i),study_id='Explicit synthetic matched-subject fixture only',omics=.iw_omics[i],scale='processed',data_csv=csv,source_sha256=digest::digest(csv,algo='sha256',serialize=FALSE))
})
mapping <- unlist(lapply(seq_along(blocks),function(i) lapply(1:8,function(j)list(block=blocks[[i]]$id,column=paste0('assay',i,'_',j),subject=subjects[j],group=if(j<=4)'simulated_control' else 'simulated_treated'))),recursive=FALSE)
p <- list(version=1L,blocks=blocks,mapping=mapping,missing_policy='reject',allow_unmatched=FALSE,preprocessing_reviewed=TRUE,design_reviewed=TRUE,confirmed=TRUE)
preview <- emp_iw_preview(p);stopifnot(length(preview$blocks)==6,!preview$analysis_executed)
result <- emp_iw_compute(p);stopifnot(nrow(result$scores)==8,nrow(result$associations)==15*36,result$execution_performed,!result$preprocessing$imputation)
first <- result$associations[1,];mats <- emp_iw_validate(p)$matrices
direct <- suppressWarnings(cor.test(mats[[first$block_a]][first$feature_a,],mats[[first$block_b]][first$feature_b,],method='spearman',exact=FALSE))
stopifnot(abs(first$pvalue-direct$p.value)<1e-12,all(result$associations$padj>=result$associations$pvalue))
fail <- function(value){stopifnot(inherits(try(emp_iw_validate(value),silent=TRUE),'try-error'))}
bad <- p;bad$blocks[[1]]$scale <- 'raw_counts';fail(bad)
bad <- p;bad$design_reviewed <- FALSE;fail(bad)
bad <- p;bad$mapping[[2]]$subject <- bad$mapping[[1]]$subject;fail(bad)
bad <- p;bad$mapping[[9]]$group <- 'contradiction';fail(bad)
bad <- p;for(j in 9:16)bad$mapping[[j]]$subject<-paste0('independent_cohort_',j);fail(bad)
bad <- p;bad$blocks[[1]]$data_csv <- sub('-?[0-9]+\\.[0-9]+','NA',bad$blocks[[1]]$data_csv);fail(bad)
bad$missing_policy <- 'exclude_features';ok <- emp_iw_validate(bad);stopifnot(length(ok$exclusions[[1]]$incomplete_features)==1)
out <- '.local_run/verification/integration-20261107';dir.create(out,recursive=TRUE,showWarnings=FALSE)
jsonlite::write_json(p,file.path(out,'synthetic-input.json'),auto_unbox=TRUE,pretty=TRUE)
jsonlite::write_json(result,file.path(out,'results.json'),auto_unbox=TRUE,pretty=TRUE,na='null')
for(i in seq_along(blocks))writeLines(blocks[[i]]$data_csv,file.path(out,paste0('synthetic-',.iw_omics[i],'.csv')))
message('Six-modality matched-subject integration and fail-closed validation: passed')
