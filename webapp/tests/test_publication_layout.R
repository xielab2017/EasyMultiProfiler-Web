source('webapp/backend/helpers/utils.R')
source('webapp/backend/helpers/plot_theme.R')
source('webapp/backend/helpers/viz.R')
profile<-list(font_pt=10,min_font_pt=8,label_mode='auto')
style<-list(export_size=list(width_mm=180,height_mm=120,dpi=150),publication=profile,figure_scale=.5)
emp_viz_style_begin(style)
root<-Sys.getenv('EMP_PUBLICATION_PROOF_DIR',tempfile('publication-proof-'));dir.create(root,recursive=TRUE,showWarnings=FALSE)
p<-ggplot2::ggplot(mtcars,ggplot2::aes(wt,mpg))+ggplot2::geom_point()+ggplot2::geom_text(ggplot2::aes(label=rownames(mtcars)),size=1)+ggplot2::labs(title='A long scientific chart heading for an A4 publication panel')+ggplot2::theme_minimal(base_size=5)
prepared<-emp_publication_plot(p,180/25.4,120/25.4)
stopifnot(prepared$theme$axis.text.x$size==10,abs(prepared$layers[[2]]$aes_params$size-10/(72.27/25.4))<1e-10,p$layers[[2]]$aes_params$size==1)
save_plot_pdf(p,file.path(root,'typography.pdf'))
set.seed(108);mat<-matrix(rexp(200*8),200,dimnames=list(paste0('GENE_',1:200),paste0('S',1:8)))
out<-.viz_render_pheatmap(mat,rep(c('Control','Drug'),each=4),'200 features (z-scored)','All matrix values retained',pdf_path=file.path(root,'heatmap.pdf'))
writeBin(base64enc::base64decode(out$png),file.path(root,'heatmap.png'))
notes<-getOption('emp.publication_notes');stopifnot(any(grepl('Feature labels:',notes,fixed=TRUE)))
emp_viz_style_begin(list(export_size=list(width_mm=50.8,height_mm=50.8,dpi=150),publication=profile))
error<-tryCatch({.viz_render_pheatmap(mat,rep(c('Control','Drug'),each=4),'Heatmap');NULL},error=identity)
stopifnot(inherits(error,'error'),grepl('Publication layout too small',conditionMessage(error)))
profile$label_mode<-'strict';style$publication<-profile;emp_viz_style_begin(style)
error<-tryCatch({.viz_render_pheatmap(mat,rep(c('Control','Drug'),each=4),'Heatmap');NULL},error=identity)
stopifnot(inherits(error,'error'),grepl('Publication labels too dense',conditionMessage(error)))
for(size in list(list(font_pt=7,min_font_pt=8,label_mode='auto'),list(font_pt=10,min_font_pt=0,label_mode='auto')))stopifnot(inherits(tryCatch(emp_publication_validate(size),error=identity),'error'))
cat('PASS publication typography, immutable text layers, sparse heatmap labels, 2-inch layout rejection, strict-label validation\nProofs:',root,'\n')

