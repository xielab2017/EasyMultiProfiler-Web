#!/usr/bin/env Rscript
# Reproduce reviewed exploration locally. Never evaluates user R/formulas or overwrites an output.
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 2L) stop('Usage: Rscript webapp/scripts/run_integration_workflow.R input.json new-output-directory')
script <- sub('^--file=', '', commandArgs()[grepl('^--file=', commandArgs())][1])
source(file.path(dirname(normalizePath(script)), '../backend/helpers/integration_workbench.R'))
if (dir.exists(args[2]) || file.exists(args[2])) stop('Choose a new output directory; existing results are preserved')
payload <- jsonlite::read_json(args[1], simplifyVector = FALSE)
result <- emp_iw_compute(payload)
dir.create(args[2], recursive = TRUE)
jsonlite::write_json(result,file.path(args[2],'integration-results.json'),auto_unbox=TRUE,pretty=TRUE,na='null')
utils::write.table(result$scores,file.path(args[2],'joint-pca.tsv'),sep='\t',quote=TRUE,row.names=FALSE)
utils::write.table(result$associations,file.path(args[2],'cross-omics-associations.tsv'),sep='\t',quote=TRUE,row.names=FALSE)
utils::write.csv(result$scores,file.path(args[2],'joint-pca.csv'),row.names=FALSE)
grDevices::pdf(file.path(args[2],'joint-pca.pdf'),width=7,height=5)
groups<-factor(result$scores$group)
graphics::plot(result$scores$PC1,result$scores$PC2,col=as.integer(groups),pch=19,xlab=sprintf('PC1 (%.1f%%)',100*result$variance_explained[[1]]),ylab=sprintf('PC2 (%.1f%%)',100*result$variance_explained[[2]]),main='Exploratory block-balanced PCA')
graphics::legend('topright',legend=levels(groups),col=seq_along(levels(groups)),pch=19,bty='n')
grDevices::dev.off()
message('Completed reviewed exploratory integration: ',normalizePath(args[2]))
